"""课表/日程内核（scheduler）—— agent 的"确定性裁决"层

【这一层为什么存在】
    大模型很擅长把一段乱七八糟的文字读成结构化的东西（"周四 19:00 班会"），
    但它不可靠：它会自信地说"你周四晚上有空"，而它根本不知道你有课。

    所以本项目把职责劈成两半：

        模型  →  提议（propose）：从自然语言里抽取事件、提出候选时间
        内核  →  裁决（decide） ：这个时间到底成不成立，只有这里说了算

    内核里**没有任何模型调用、没有任何随机性**：同一份输入，永远得到同一个答案。
    这是整个项目的地基 —— 它必须能被信任，也必须能被测试。

【模块】
    model.py    数据模型（事件、重复规则、校验）
    store.py    落库（JSONL，追加式，可 diff）
    conflict.py 冲突检测 + 找空档 + 替代方案
    ics.py      导出 .ics（同步到手机系统日历）
    cli.py      命令行入口

【依赖】
    只依赖 Python 标准库。故意不引入 dateutil / pandas —— 让这个内核在任何机器上
    `python -m scheduler` 就能跑，也让它可测试。
"""
